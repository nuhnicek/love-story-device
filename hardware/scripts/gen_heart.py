"""
Schematic for the heart LED board (separate PCB, wired to carrier pads HT1/HT2).

  python3 hardware/scripts/gen_heart.py   ->  hardware/heart/heart-led.kicad_sch

14 pink 0603 LEDs, each with its own 330 R (pink LEDs need about 2.9 V and their Vf
varies a lot, so a shared resistor would make some LEDs much brighter than others).
The resistors are four 4 x 0402 arrays (RN1-RN4, two spare) in the middle of the heart.
"""
import os
import schlib

HW = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = os.path.join(HW, "heart")
PROJECT = "heart-led"
N_LEDS = 14
R_VAL = "330R"

S = schlib.Sheet(PROJECT, os.path.join(DIR, PROJECT + ".kicad_sch"), power={},
                 seed="0e7c3a52-9d11-4f4b-8a07-5c2b1e9d4f61")

S.box(15.24, 22.86, 281.94, 160.02, "Heart LED board: 14 x pink 0603, one 330 R per LED (4 x 4-resistor arrays)")
# resistor arrays: resistor i of RNk feeds LED 4(k-1)+i; pins 1-4 = LED+, pins 8..5 = anodes
for k in range(4):
    nets, nc = {}, []
    for i in range(4):
        led = 4 * k + i + 1
        if led <= N_LEDS:
            nets[str(i + 1)] = "LED+"
            nets[str(8 - i)] = "A%d" % led
        else:
            nc += [str(i + 1), str(8 - i)]
    S.place("Device:R_Pack04", "RN%d" % (k + 1), R_VAL + " x4", 45.72 + k * 55.88, 50.8, 0,
            "Resistor_SMD:R_Array_Convex_4x0402", nets, nc=tuple(nc))
for i in range(N_LEDS):
    col, row = i % 7, i // 7
    S.place("Device:LED", "D%d" % (i + 1), "LED pink 0603", 30.48 + col * 35.56, 86.36 + row * 20.32, 0,
            "LED_SMD:LED_0603_1608Metric", {"1": "LED-", "2": "A%d" % (i + 1)})

S.place("Connector:TestPoint", "HP1", "LED+", 30.48, 142.24, 180, "keychain:WirePad_1.0mm",
        {"1": "LED+"}, in_bom=False)
S.place("Connector:TestPoint", "HP2", "LED-", 50.8, 147.32, 0, "keychain:WirePad_1.0mm",
        {"1": "LED-"}, in_bom=False)
S.text("HP1 (LED+) -> carrier HT1 (HEART+, = VBAT)", 63.5, 139.7)
S.text("HP2 (LED-) -> carrier HT2 (HEART-, = AO3400A drain, PWM on PB4)", 63.5, 142.24)
S.text("I_LED = (V_BAT - Vf 2.9 V) / 330 R  =  1.5 mA @ 3.4 V ... 4 mA @ 4.2 V  (max ~55 mA total)", 63.5, 147.32)
S.text("Pink LEDs dim noticeably below ~3.5 V battery - that's a useful 'charge me' hint.", 63.5, 149.86)

S.write("GSM touch keychain - heart LED board",
        ["14 x pink 0603 LED, heart-shaped PCB, wired to the carrier",
         "Generated by hardware/scripts/gen_heart.py - edit the script, not this file"],
        os.path.join(DIR, "sch_uuids.json"))
schlib.write_lib_tables(DIR, "../keychain.kicad_sym", "../keychain.pretty")
print("heart schematic:", S.out, "symbols:", len(S.uuids))
